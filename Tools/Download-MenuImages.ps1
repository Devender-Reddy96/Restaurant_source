<#
 Downloads a sample photo for each menu item from Wikipedia / Wikimedia Commons and
 writes a SQL file that attaches the images to your Food Items.

 Run on a PC with internet (PowerShell 5.1 or 7):
   .\Download-MenuImages.ps1   (run from the Tools folder; defaults already point at the project)

 Then run the generated 03_MenuImagePaths.sql in pgAdmin (after 02_MenuSeed_SouthIndia_India.sql).

 Notes
 - Items with no Wikipedia photo are skipped; the order screen shows an icon for them.
 - Wikimedia images carry their own licences (mostly CC BY / CC BY-SA). menu_images_credits.csv
   lists the source page of every file - keep it, and give credit if you publish the menu.
 - Several variants share one dish photo (e.g. all Kothu Parotta types). Replace with your own
   photos any time under Food Items > Edit > Photo.
#>
param(
    [string]$Csv    = (Join-Path $PSScriptRoot "menu_items.csv"),
    [string]$OutDir = (Join-Path $PSScriptRoot "..\RestaurantManagement\wwwroot\uploads\menu"),
    [string]$SqlOut = (Join-Path $PSScriptRoot "..\Database\03_MenuImagePaths.sql"),
    [string]$WebPath = "/uploads/menu",
    [int]$Width = 500,
    [string]$UserAgent = "RestaurantMenuImageFetcher/1.0 (set-your-email@example.com)"
)

$ErrorActionPreference = "Continue"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
New-Item -ItemType Directory -Force -Path (Split-Path $SqlOut) | Out-Null

$rows    = Import-Csv -Path $Csv -Encoding UTF8
$cache   = @{}      # wikipedia title -> @{ File=..; Page=.. } or $null
$sql     = New-Object System.Collections.Generic.List[string]
$credits = New-Object System.Collections.Generic.List[object]
$ok = 0; $miss = 0

$sql.Add("-- Attach downloaded images to food items (generated by Download-MenuImages.ps1)")
$sql.Add("BEGIN;")

foreach ($r in $rows) {
    $title = $r.wikipedia_title
    if ([string]::IsNullOrWhiteSpace($title)) { $miss++; continue }

    if (-not $cache.ContainsKey($title)) {
        $cache[$title] = $null
        try {
            $api  = "https://en.wikipedia.org/api/rest_v1/page/summary/" + [Uri]::EscapeDataString($title.Replace(' ', '_'))
            $info = Invoke-RestMethod -Uri $api -UserAgent $UserAgent -TimeoutSec 30
            $src  = $null
            if ($info.thumbnail -and $info.thumbnail.source) { $src = $info.thumbnail.source }
            elseif ($info.originalimage -and $info.originalimage.source) { $src = $info.originalimage.source }
            if ($src) {
                $big = $src -replace '/\d+px-', "/${Width}px-"
                $ext = [IO.Path]::GetExtension(($src -split '\?')[0]).ToLower()
                if ($ext -notin '.jpg', '.jpeg', '.png', '.webp') { $ext = '.jpg' }
                $safe = ($title -replace '[^A-Za-z0-9]+', '_').Trim('_')
                $file = "$safe$ext"
                $path = Join-Path $OutDir $file
                if (-not (Test-Path $path)) {
                    try   { Invoke-WebRequest -Uri $big -OutFile $path -UserAgent $UserAgent -TimeoutSec 60 }
                    catch { Invoke-WebRequest -Uri $src -OutFile $path -UserAgent $UserAgent -TimeoutSec 60 }
                }
                if (Test-Path $path) {
                    $cache[$title] = @{ File = $file; Page = $info.content_urls.desktop.page }
                }
            }
        } catch { Write-Warning "No image for '$title': $($_.Exception.Message)" }
        Start-Sleep -Milliseconds 250
    }

    $hit = $cache[$title]
    if ($hit) {
        $ok++
        $code = $r.item_code.Replace("'", "''")
        $sql.Add("UPDATE menu.food_item_master SET image_path = '$WebPath/$($hit.File)' WHERE item_code = '$code';")
        $credits.Add([pscustomobject]@{ item_code = $r.item_code; food_name = $r.food_name; image_file = $hit.File; source_page = $hit.Page })
    } else { $miss++ }
}

$sql.Add("COMMIT;")
$sql | Set-Content -Path $SqlOut -Encoding UTF8
$credits | Export-Csv -Path (Join-Path $OutDir "menu_images_credits.csv") -NoTypeInformation -Encoding UTF8

Write-Host ""
Write-Host "Items linked to an image : $ok"
Write-Host "Items without an image   : $miss"
Write-Host "Images folder            : $OutDir"
Write-Host "SQL file                 : $SqlOut"
